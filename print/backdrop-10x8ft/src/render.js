const { chromium } = require('playwright');
const path = require('path'); const D = path.resolve(__dirname, '..');
(async()=>{const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1220,height:980}});
await p.goto('file://'+__dirname+'/banner.html');await p.waitForFunction(()=>window.__ready);await p.waitForTimeout(800);
await p.pdf({path:D+'/golf-games-classic-banner-10x8ft.pdf',width:'122in',height:'98in',printBackground:true,pageRanges:'1'});
const q=await b.newPage({viewport:{width:1220,height:980},deviceScaleFactor:2});
await q.goto('file://'+__dirname+'/banner.html');await q.waitForFunction(()=>window.__ready);
await q.addStyleTag({content:'#art{width:1220px!important;height:980px!important}'});await q.waitForTimeout(800);
await q.screenshot({path:D+'/preview.png',clip:{x:0,y:0,width:1220,height:980}});
await b.close();})();
