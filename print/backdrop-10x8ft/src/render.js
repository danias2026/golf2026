const { chromium } = require('playwright');
(async()=>{const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1220,height:980}});
await p.goto('file://'+__dirname+'/backdrop.html');await p.waitForFunction(()=>window.__ready);await p.waitForTimeout(800);
await p.pdf({path:__dirname+'/../golf-games-classic-backdrop-10x8ft.pdf',width:'122in',height:'98in',printBackground:true,pageRanges:'1'});
await p.setViewportSize({width:1220,height:980});
await p.evaluate(()=>{const a=document.getElementById('art');a.style.width='1220px';a.style.height='980px';});
const p2=await b.newPage({viewport:{width:1220,height:980},deviceScaleFactor:2});
await p2.goto('file://'+__dirname+'/backdrop.html');await p2.waitForFunction(()=>window.__ready);
await p2.addStyleTag({content:'#art{width:1220px!important;height:980px!important}'});await p2.waitForTimeout(800);
await p2.screenshot({path:__dirname+'/../preview.png',clip:{x:0,y:0,width:1220,height:980}});
await b.close();})();
