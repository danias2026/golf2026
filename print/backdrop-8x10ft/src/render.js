const { chromium } = require('playwright');
(async()=>{const b=await chromium.launch();
const p=await b.newPage({viewport:{width:980,height:1220}});
await p.goto('file://'+__dirname+'/backdrop.html');await p.waitForFunction(()=>window.__ready);await p.waitForTimeout(800);
await p.pdf({path:__dirname+'/../golf-games-classic-backdrop-8x10ft.pdf',width:'98in',height:'122in',printBackground:true,pageRanges:'1'});
await p.setViewportSize({width:980,height:1220});
await p.evaluate(()=>{const a=document.getElementById('art');a.style.width='980px';a.style.height='1220px';});
const p2=await b.newPage({viewport:{width:980,height:1220},deviceScaleFactor:2});
await p2.goto('file://'+__dirname+'/backdrop.html');await p2.waitForFunction(()=>window.__ready);
await p2.addStyleTag({content:'#art{width:980px!important;height:1220px!important}'});await p2.waitForTimeout(800);
await p2.screenshot({path:__dirname+'/../preview.png',clip:{x:0,y:0,width:980,height:1220}});
await b.close();})();
